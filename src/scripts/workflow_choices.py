# Added in the morphe-autobuilder-v2 fork: GitHub's "Run workflow" dropdowns
# only accept a fixed list of options, so this writes every brand in
# config.toml into the marked option lists of the workflows.
#
#   python -m src.scripts.workflow_choices [--check]

import argparse
import re
import sys
from pathlib import Path

from src.core.config import CONFIG_PATH, load_toml, parse_app_entries, parse_config

WORKFLOWS = (Path(".github/workflows/ci.yml"), Path(".github/workflows/build.yml"))
_BLOCK = re.compile(r"(?P<indent>[ ]*)# >>> brands[^\n]*\n.*?(?P=indent)# <<< brands <<<", re.DOTALL)


def brands() -> list[str]:
    data = load_toml(CONFIG_PATH)
    found = {e.brand.lower() for e in parse_app_entries(data, parse_config(data)) if e.enabled}
    # The two original sources first (they are the defaults), the rest alphabetically.
    return [b for b in ("morphe", "piko") if b in found] + sorted(found - {"morphe", "piko"})

def render(text: str, names: list[str]) -> str:
    def fill(m: re.Match[str]) -> str:
        ind = m["indent"]
        lines = [f"{ind}# >>> brands (generated by `python -m src.scripts.workflow_choices`) >>>"]
        lines += [f"{ind}- {n}" for n in names]
        lines.append(f"{ind}# <<< brands <<<")
        return "\n".join(lines)
    return _BLOCK.sub(fill, text)

def sync(check: bool = False) -> bool:
    """Rewrite the option lists; with check=True only report whether they are current."""
    names = brands()
    stale = False
    for wf in WORKFLOWS:
        text = wf.read_text(encoding="utf-8")
        if not _BLOCK.search(text):
            continue
        new = render(text, names)
        if new != text:
            stale = True
            if not check:
                wf.write_text(new, encoding="utf-8")
                print(f"Updated {wf} ({len(names)} patch sources)")
    return not stale

def main() -> None:
    parser = argparse.ArgumentParser(prog="python -m src.scripts.workflow_choices", description="Write config.toml's brands into the workflow dropdowns.")
    parser.add_argument("--check", action="store_true", help="Exit 1 if the dropdowns are out of date instead of rewriting them")
    args = parser.parse_args()
    current = sync(check=args.check)
    if args.check and not current:
        print("Workflow dropdowns are out of date: run `python -m src.scripts.workflow_choices`")
        sys.exit(1)
    if current and not args.check:
        print("Workflow dropdowns already up to date")

if __name__ == "__main__":
    main()
